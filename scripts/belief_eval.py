"""Emit the M3-3 belief-evaluation evidence table (PRD_belief section 3 DoD).

Runs the same seeded referee-mode trials as tests/integration/test_belief_vs_baseline.py
and writes docs/evidence/m3-belief-eval.md. Deterministic: same tree + config -> same
table, so the committed artifact is reproducible by any reviewer with one command:

  uv run python scripts/belief_eval.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from copthief_core.domain.scent_models import make_scent_model  # noqa: E402
from copthief_core.shared.config import load_all  # noqa: E402
from copthief_core.shared.locked_models import SCENT_MODEL  # noqa: E402
from copthief_core.strategy.belief_eval import TrialResult, run_belief_trial  # noqa: E402

SEEDS = range(1, 11)
OUT = Path("docs/evidence/m3-belief-eval.md")
# M3-8: every registered model is measured. ADR-0004 v2's consequences section forbids
# quoting an M3-3 number for a model it was not measured under.
MODELS = ("subtractive_chebyshev_v1", "multiplicative_book_v1")


def _header() -> list[str]:
    return [
        "# M3-3 belief evaluation - exact Bayes filter vs last-known-position baseline",
        "",
        "> Generated by `uv run python scripts/belief_eval.py` (deterministic; regenerate,",
        "> never hand-edit). Referee-mode trials on the shipped config: a seeded legal",
        "> opponent walks `survival_threshold` steps emitting its honest locked-model",
        "> trail; both trackers consume the same transmitted grids blind.",
        "> Primary metric `belief_error = 1 - P(truth)` per step, averaged; secondary =",
        "> argmax-hit-rate. Baseline reads only protocol-certain evidence (the signed",
        "> start) - scent grids are unauthenticated (SQ3) and a naive tracker trusting",
        "> them would be trivially spoofable.",
        "",
        "> **M3-8: measured PER NAMED MODEL.** The trail and the filter's observation",
        "> model are the same model in each run, so no number here is quoted for a model",
        "> it was not measured under (ADR-0004 v2). Caveat for `multiplicative_book_v1`:",
        "> this is a REFEREE-MODE instrument that feeds the tracker the emitted grid",
        "> directly. Its registration sets `transmitted: false`, so in a live game a peer",
        "> honouring that would put no grid on the wire at all and the scent channel",
        "> would carry nothing (open item: PRD_scent s9.3, TODO M3-8).",
        "",
        "> **Why the book model scores so much worse, mechanistically** (probed, not",
        "> assumed - two separable causes, and only the first is inherent to the model):",
        "> **(1) Saturation.** Its deposit is ADDITIVE with an upper clamp at",
        "> `center_intensity`, so on the signed 7x7 board with a 5x5 kernel a cell",
        "> revisited within ring 1 reaches `0.9*0.9 + 0.62 = 1.43` and pins at 0.9. A",
        "> sample walk puts 12 of 49 cells at the ceiling by turn 4, so 'the freshest",
        "> cell' stops identifying the current position. That is the registered model's",
        "> own arithmetic - the same clamp case the kit fixture pins.",
        "> **(2) Ring/age conflation, which is OUR machinery, not the book's.** The",
        "> voucher heuristic reads an intensity as an AGE. Inverting logarithmically, a",
        "> FRESH ring-1 cell (0.62) reads as age 4 and a fresh ring-2 cell (0.20) as age",
        "> 14, spreading vouchers over huge Manhattan balls. A filter designed for this",
        "> model would treat the kernel as a spatial likelihood rather than an age.",
        "> So this table is an honest re-measurement of the CURRENT filter under both",
        "> models - it is not evidence that the book's physics is unusable in principle.",
        "",
    ]


def _table(results: list[TrialResult], model: str) -> str:
    lines = [
        f"## `{model}`",
        "",
        "| seed | steps | filter mean error | baseline mean error | filter hit-rate | baseline hit-rate |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {r.seed} | {r.steps} | {r.filter_mean_error:.4f} | {r.baseline_mean_error:.4f}"
        f" | {r.filter_hit_rate:.3f} | {r.baseline_hit_rate:.3f} |"
        for r in results
    ]
    n = len(results)
    filter_mean = sum(r.filter_mean_error for r in results) / n
    baseline_mean = sum(r.baseline_mean_error for r in results) / n
    filter_hits = sum(r.filter_hit_rate for r in results) / n
    baseline_hits = sum(r.baseline_hit_rate for r in results) / n
    lines += [
        f"| **mean** | | **{filter_mean:.4f}** | **{baseline_mean:.4f}**"
        f" | **{filter_hits:.3f}** | **{baseline_hits:.3f}** |",
        "",
        f"**Verdict (`{model}`):** filter mean error {filter_mean:.4f} vs baseline"
        f" {baseline_mean:.4f}, winning the primary metric on"
        f" {sum(r.filter_mean_error < r.baseline_mean_error for r in results)}/{n} seeds;"
        f" its argmax finds the true cell {filter_hits:.0%} of steps vs the baseline's"
        f" {baseline_hits:.0%}. CI enforces the SHIPPED model's claim in"
        " `tests/integration/test_belief_vs_baseline.py`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    constitution, private, _limits = load_all(Path("config"), counted=False)
    sections = _header()
    total = 0
    for model in MODELS:
        doc = private.locked_models.doc(SCENT_MODEL, model)
        results = [
            run_belief_trial(
                constitution,
                smell_trust=private.smell_trust_weight,
                seed=seed,
                steps=constitution.movement.survival_threshold,
                scent_model=make_scent_model(model, params=doc["params"]),
            )
            for seed in SEEDS
        ]
        sections.append(_table(results, model))
        total += len(results)
    OUT.write_text("\n".join(sections), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({total} trials over {len(MODELS)} models)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
